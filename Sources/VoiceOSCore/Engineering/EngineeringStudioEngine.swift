import Foundation

public enum CADBackend: String, Codable, Sendable, CaseIterable {
    case openscad = "OpenSCAD"
    case cadquery = "CadQuery"
}

public enum CADShapeKind: String, Codable, Sendable, CaseIterable {
    case bracket
    case gear
    case enclosure
    case heatsink
}

public struct CADGenerationResult: Sendable, Equatable {
    public let backend: CADBackend
    public let shape: CADShapeKind
    public let title: String
    public let sourceCode: String
    public let hologramHTML: String
    public let exportedFilePath: String?
}

public struct PhysicsSimulationResult: Sendable, Equatable {
    public let simulationType: String
    public let summary: String
    public let metrics: [String: Double]
    public let trajectoryPoints: [(x: Double, y: Double)]

    public static func == (lhs: PhysicsSimulationResult, rhs: PhysicsSimulationResult) -> Bool {
        lhs.simulationType == rhs.simulationType &&
        lhs.summary == rhs.summary &&
        lhs.metrics == rhs.metrics &&
        lhs.trajectoryPoints.count == rhs.trajectoryPoints.count
    }
}

public protocol EngineeringCADGenerating: Sendable {
    func generateCAD(shape: CADShapeKind, backend: CADBackend, widthMM: Double, heightMM: Double, depthMM: Double) -> CADGenerationResult
}

public protocol PhysicsSimulating: Sendable {
    func simulateProjectile(velocityMS: Double, angleDegrees: Double, gravity: Double) -> PhysicsSimulationResult
    func simulateSpringHarmonic(massKg: Double, springConstantNM: Double, damping: Double, durationSeconds: Double) -> PhysicsSimulationResult
    func simulateThermal(powerWatts: Double, ambientCelsius: Double, thermalResistanceCW: Double) -> PhysicsSimulationResult
}

/// Engineering studio generating OpenSCAD / CadQuery parametric CAD code,
/// running deterministic physics simulations, and producing offline interactive 3D Hologram HTML views.
public final class EngineeringStudioEngine: EngineeringCADGenerating, PhysicsSimulating, @unchecked Sendable {
    public static let shared = EngineeringStudioEngine()

    public init() {}

    public func inferShape(from prompt: String) -> CADShapeKind {
        let lower = prompt.lowercased()
        if lower.contains("gear") || lower.contains("cog") { return .gear }
        if lower.contains("enclosure") || lower.contains("box") || lower.contains("case") { return .enclosure }
        if lower.contains("heatsink") || lower.contains("fin") || lower.contains("cooler") { return .heatsink }
        return .bracket
    }

    public func generateCAD(
        shape: CADShapeKind,
        backend: CADBackend = .openscad,
        widthMM: Double = 60,
        heightMM: Double = 40,
        depthMM: Double = 10
    ) -> CADGenerationResult {
        let w = max(5, widthMM)
        let h = max(5, heightMM)
        let d = max(2, depthMM)

        let code: String
        switch backend {
        case .openscad:
            switch shape {
            case .bracket:
                code = """
                // Parametric L-Bracket generated by Voice.AI Engineering Studio
                $fn = 64;
                width = \(w); height = \(h); thick = \(d); hole_d = 5;
                difference() {
                    union() {
                        cube([width, height, thick]);
                        cube([thick, height, height]);
                    }
                    translate([width * 0.72, height * 0.5, -1]) cylinder(h = thick + 2, d = hole_d);
                    translate([-1, height * 0.5, height * 0.72]) rotate([0, 90, 0]) cylinder(h = thick + 2, d = hole_d);
                }
                """
            case .gear:
                code = """
                // Parametric Spur Gear Blank generated by Voice.AI Engineering Studio
                $fn = 72;
                outer_r = \(w / 2); bore_r = \(max(3.0, d / 2)); teeth = 16; thick = \(d);
                difference() {
                    union() {
                        cylinder(h = thick, r = outer_r * 0.85);
                        for (i = [0 : teeth - 1]) {
                            rotate([0, 0, i * (360 / teeth)])
                                translate([outer_r * 0.82, -2, 0]) cube([outer_r * 0.18, 4, thick]);
                        }
                    }
                    translate([0, 0, -1]) cylinder(h = thick + 2, r = bore_r);
                }
                """
            case .enclosure:
                code = """
                // Parametric Electronics Enclosure generated by Voice.AI Engineering Studio
                w = \(w); l = \(h); h = \(max(20, d * 2)); wall = 2.5;
                difference() {
                    cube([w, l, h]);
                    translate([wall, wall, wall]) cube([w - 2*wall, l - 2*wall, h]);
                }
                """
            case .heatsink:
                code = """
                // Parametric Finned Heatsink generated by Voice.AI Engineering Studio
                base_w = \(w); base_l = \(h); base_t = 4; fin_h = \(max(12, d)); fins = 7;
                cube([base_w, base_l, base_t]);
                for (i = [0 : fins - 1]) {
                    translate([i * ((base_w - 2) / (fins - 1)), 0, base_t])
                        cube([2, base_l, fin_h]);
                }
                """
            }
        case .cadquery:
            code = """
            import cadquery as cq
            # Parametric \(shape.rawValue) generated by Voice.AI Engineering Studio
            w, h, d = \(w), \(h), \(d)
            part = (
                cq.Workplane("XY")
                .box(w, h, d)
                .faces(">Z")
                .workplane()
                .hole(5.0)
            )
            """
        }

        let html = Self.buildHologramHTML(
            title: "\(shape.rawValue.capitalized) (\(Int(w))×\(Int(h))×\(Int(d))mm)",
            shape: shape,
            widthMM: w,
            heightMM: h,
            depthMM: d
        )

        var savedPath: String? = nil
        if ProcessInfo.processInfo.environment["VOICE_AI_TEST_MODE"] != "1" {
            let dir = FileManager.default.temporaryDirectory.appendingPathComponent("VoiceAI_CAD", isDirectory: true)
            try? FileManager.default.createDirectory(at: dir, withIntermediateDirectories: true)
            let ext = backend == .openscad ? "scad" : "py"
            let url = dir.appendingPathComponent("voiceai_\(shape.rawValue).\(ext)")
            try? code.write(to: url, atomically: true, encoding: .utf8)
            savedPath = url.path
        }

        return CADGenerationResult(
            backend: backend,
            shape: shape,
            title: "\(backend.rawValue) \(shape.rawValue.capitalized)",
            sourceCode: code,
            hologramHTML: html,
            exportedFilePath: savedPath
        )
    }

    // MARK: - Physics Simulations

    public func simulateProjectile(velocityMS: Double, angleDegrees: Double, gravity: Double = 9.81) -> PhysicsSimulationResult {
        let v = max(0.1, velocityMS)
        let g = max(0.1, gravity)
        let rad = angleDegrees * Double.pi / 180.0
        let vx = v * cos(rad)
        let vy = v * sin(rad)
        let flightTime = (2.0 * vy) / g
        let range = vx * flightTime
        let maxHeight = (vy * vy) / (2.0 * g)

        var points: [(Double, Double)] = []
        let steps = 20
        for i in 0...steps {
            let t = flightTime * (Double(i) / Double(steps))
            let x = vx * t
            let y = max(0.0, vy * t - 0.5 * g * t * t)
            points.append((x, y))
        }

        return PhysicsSimulationResult(
            simulationType: "Projectile Kinematics",
            summary: String(format: "Range %.2fm, Max Height %.2fm, Flight Time %.2fs (v=%.1fm/s @ %.1f°).", range, maxHeight, flightTime, v, angleDegrees),
            metrics: ["range_m": range, "max_height_m": maxHeight, "flight_time_s": flightTime],
            trajectoryPoints: points
        )
    }

    public func simulateSpringHarmonic(
        massKg: Double,
        springConstantNM: Double,
        damping: Double = 0.25,
        durationSeconds: Double = 5.0
    ) -> PhysicsSimulationResult {
        let m = max(0.01, massKg)
        let k = max(0.1, springConstantNM)
        let omega0 = sqrt(k / m)
        let zeta = damping / (2.0 * sqrt(m * k))
        let freqHz = omega0 / (2.0 * Double.pi)

        var pts: [(Double, Double)] = []
        let steps = 40
        for i in 0...steps {
            let t = durationSeconds * (Double(i) / Double(steps))
            let amp = exp(-zeta * omega0 * t) * cos(omega0 * sqrt(max(0.01, 1.0 - zeta * zeta)) * t)
            pts.append((t, amp))
        }

        return PhysicsSimulationResult(
            simulationType: "Damped Harmonic Oscillator",
            summary: String(format: "Natural freq %.2f Hz, damping ratio %.3f (m=%.2fkg, k=%.1fN/m).", freqHz, zeta, m, k),
            metrics: ["natural_freq_hz": freqHz, "damping_ratio": zeta, "omega0_rad_s": omega0],
            trajectoryPoints: pts
        )
    }

    public func simulateThermal(powerWatts: Double, ambientCelsius: Double = 25.0, thermalResistanceCW: Double = 1.8) -> PhysicsSimulationResult {
        let deltaT = max(0.0, powerWatts) * max(0.01, thermalResistanceCW)
        let steadyTemp = ambientCelsius + deltaT
        return PhysicsSimulationResult(
            simulationType: "Steady-State Thermal",
            summary: String(format: "Junction temperature %.1f°C (+%.1f°C above %.1f°C ambient at %.1fW).", steadyTemp, deltaT, ambientCelsius, powerWatts),
            metrics: ["steady_temp_c": steadyTemp, "delta_t_c": deltaT, "power_w": powerWatts],
            trajectoryPoints: [(0, ambientCelsius), (1, steadyTemp)]
        )
    }

    // MARK: - Self-Contained 3D Hologram Wireframe Viewer HTML (Offline WebView Ready)

    public static func buildHologramHTML(
        title: String,
        shape: CADShapeKind,
        widthMM: Double,
        heightMM: Double,
        depthMM: Double
    ) -> String {
        let sx = min(1.8, max(0.5, widthMM / 50.0))
        let sy = min(1.8, max(0.5, heightMM / 50.0))
        let sz = min(1.8, max(0.4, depthMM / 25.0))
        return """
        <!DOCTYPE html>
        <html>
        <head>
        <meta charset="utf-8"/>
        <style>
          html, body { margin:0; padding:0; background:#030812; color:#4deeea; font-family:ui-monospace,monospace; overflow:hidden; }
          #hud { position:absolute; top:10px; left:12px; font-size:11px; letter-spacing:0.6px; text-shadow:0 0 8px #00f0ff; }
          canvas { width:100vw; height:100vh; display:block; }
        </style>
        </head>
        <body>
          <div id="hud">HOLOGRAM VIEWER // \(title)</div>
          <canvas id="c"></canvas>
          <script>
            const canvas = document.getElementById('c');
            const ctx = canvas.getContext('2d');
            function resize(){ canvas.width = window.innerWidth; canvas.height = window.innerHeight; }
            window.addEventListener('resize', resize); resize();
            const sx = \(sx), sy = \(sy), sz = \(sz);
            const verts = [
              [-sx,-sy,-sz],[sx,-sy,-sz],[sx,sy,-sz],[-sx,sy,-sz],
              [-sx,-sy,sz],[sx,-sy,sz],[sx,sy,sz],[-sx,sy,sz]
            ];
            const edges = [[0,1],[1,2],[2,3],[3,0],[4,5],[5,6],[6,7],[7,4],[0,4],[1,5],[2,6],[3,7]];
            let angle = 0;
            function draw(){
              ctx.fillStyle = '#030812';
              ctx.fillRect(0, 0, canvas.width, canvas.height);
              angle += 0.015;
              const ca = Math.cos(angle), sa = Math.sin(angle);
              const proj = verts.map(([x,y,z]) => {
                const rx = x * ca - z * sa;
                const rz = x * sa + z * ca + 4.2;
                const ry = y * 0.9 - rz * 0.08;
                const f = Math.min(canvas.width, canvas.height) * 0.42 / rz;
                return [canvas.width/2 + rx * f, canvas.height/2 + ry * f];
              });
              ctx.strokeStyle = '#3ef5ff';
              ctx.shadowBlur = 12;
              ctx.shadowColor = '#00e5ff';
              ctx.lineWidth = 1.6;
              ctx.beginPath();
              for (const [a,b] of edges){
                ctx.moveTo(proj[a][0], proj[a][1]);
                ctx.lineTo(proj[b][0], proj[b][1]);
              }
              ctx.stroke();
              requestAnimationFrame(draw);
            }
            draw();
          </script>
        </body>
        </html>
        """
    }
}

